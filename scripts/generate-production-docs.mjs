// Generates docs/PRODUCTION_STAGES.md (per-stage wiring diagrams, configs, faults, cues, pass criteria) and
// docs/PRODUCTION_EQUIPMENT_MANIFEST.md from game/training/sim. It also replays every stage headlessly with the
// test solver and records the result (mission test records). Usage: node scripts/generate-production-docs.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SCENARIOS, MODELS, STAGES, solve, load } from "../tests/helpers/solver.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { ROOMS } = load("../game/training/sim/rooms.ts");
const { PREFLIGHT } = load("../game/training/sim/stages.ts");
const { stageScore } = load("../game/training/hdmi-training.ts");

const name = (room, port) => {
  const [dev, key] = port.split(":");
  const inst = ROOMS[room].instances[dev];
  const p = MODELS[inst.model].ports.find((x) => x.key === key);
  return `${inst.label} · ${p.name}`;
};
const lines = ["# Production stages — wiring diagrams, start states and pass criteria", "", "_Generated by `node scripts/generate-production-docs.mjs` from `game/training/sim/stages.ts`. Do not edit by hand._", ""];
for (const room of Object.keys(ROOMS)) {
  const r = ROOMS[room];
  lines.push(`## ${r.code} · ${r.title}`, `_${r.subtitle}_`, "");
  for (const s of STAGES.filter((x) => x.room === room)) {
    const id = `${room}-${s.level}`;
    lines.push(`### ${s.id} / L${s.level} — ${s.title} (${s.guidance}; ${s.minutes})`, "", `**Ticket:** ${s.ticket}`, "", "**Canonical graph**", "", "```");
    for (const [f, t] of s.solution) lines.push(`${name(room, f)}  ->  ${name(room, t)}`);
    lines.push("```", "");
    const cfg = s.solutionConfig.filter((c) => c.device !== "site").map((c) => `${c.device}.${c.key} = ${c.value}`);
    lines.push(`**Operator configuration (ground truth):** ${cfg.join("; ") || "—"}`, "");
    if (s.prewired) lines.push(`**Start state:** ${s.prewired === "all" ? "fully pre-wired show" : `pre-wired: ${s.prewired.map(([f, t]) => `${name(room, f)} -> ${name(room, t)}`).join("; ")}`}`, "");
    if (s.startConfig?.length) lines.push(`**Start config:** ${s.startConfig.map((c) => `${c.device}.${c.key} = ${c.value}`).join("; ")}`, "");
    if (s.faults?.length) lines.push(`**Seeded faults:** ${s.faults.map((f) => `${f.label} [${f.concept}]`).join("; ")}`, "");
    if (s.surpriseFaults?.length) lines.push(`**Surprise fault pool (one, chosen from the attempt seed after rehearsal):** ${s.surpriseFaults.map((f) => f.label).join("; ")}`, "");
    if (s.extraCables?.length) lines.push(`**Spares / decoys in the kit:** ${s.extraCables.map((c) => c.label).join("; ")}`, "");
    if (s.decoys?.length) lines.push(`**Decoy devices:** ${s.decoys.join(", ")}`, "");
    if (s.cues.length) lines.push(`**Run-of-show:** ${s.cues.map((c) => `${c.call} → ${c.expect}`).join(" · ")}${s.previewBeforeTake ? " (preview before every TAKE)" : ""}`, "");
    if (s.preflight.length) lines.push(`**Preflight:** ${s.preflight.map((k) => PREFLIGHT[k]).join("; ")}`, "");
    lines.push(`**Objectives (${s.objectives.length}, ★ = critical gate):**`, "", ...s.objectives.map((o) => `- [${o.stage} · ${o.category}] ${o.label}${o.critical ? " ★" : ""}`), "");
    lines.push(`**Pass criteria (spec):** ${s.passCriteria.join("; ")}`, "", `**Reward:** ${s.reward}`, "");
    void id;
  }
}
fs.writeFileSync(path.join(root, "docs/PRODUCTION_STAGES.md"), lines.join("\n"));

const eq = ["# Equipment manifest", "", "_Generated from `game/training/sim/equipment.ts`._", "", "| Model id | Manufacturer / name | Source | Verified / defined ports | Asset licence |", "|---|---|---|---|---|"];
for (const m of Object.values(MODELS)) eq.push(`| ${m.modelId} | ${m.manufacturer} · ${m.name} | ${m.sourceUrl ?? "Generic Training Device (room specification)"} | ${m.verifiedPorts.join("; ")} | ${m.assetLicense} |`);
fs.writeFileSync(path.join(root, "docs/PRODUCTION_EQUIPMENT_MANIFEST.md"), eq.join("\n") + "\n");

const rec = ["# Mission test records (headless replay)", "", `_Generated ${new Date().toISOString().slice(0, 10)} by \`node scripts/generate-production-docs.mjs\` — every stage is played through the public game transitions (carry, plug, configure, tests, cues, faults, sign-off)._`, "", "| Stage | Result | Score | Grade | Evidence items | Faults recovered | Cues |", "|---|---|---|---|---|---|---|"];
for (const id of Object.keys(SCENARIOS).filter((x) => SCENARIOS[x].stage)) {
  const s = solve(id);
  const score = stageScore(s);
  rec.push(`| ${s.sim.stageId} | ${s.completed ? "COMPLETED" : "FAILED"} | ${score?.score ?? "—"} | ${score?.grade ?? "—"} | ${s.sim.evidence.length} | ${s.sim.recovered.join(", ") || "—"} | ${s.sim.cueIndex}/${SCENARIOS[id].stage.cues.length} |`);
}
fs.writeFileSync(path.join(root, "docs/PRODUCTION_TEST_RECORDS.md"), rec.join("\n") + "\n");
console.log("docs written");
